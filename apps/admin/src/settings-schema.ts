/** Schema shared by the local SQLite store and the production PostgreSQL store. */
export function settingsSchema(backend: 'sqlite' | 'postgres'): string {
  const postgres = backend === 'postgres';
  const integer = postgres ? 'BIGINT' : 'INTEGER';
  const real = postgres ? 'DOUBLE PRECISION' : 'REAL';
  const identity = postgres
    ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
    : 'INTEGER PRIMARY KEY';
  const auditId = postgres ? identity : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const loginFailureId = postgres ? `  id ${identity},\n` : '';
  return `
CREATE TABLE IF NOT EXISTS admin_users (
  id ${identity},
  name TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at ${integer} NOT NULL,
  updated_at ${integer} NOT NULL,
  disabled ${integer} NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sessions (
  id TEXT PRIMARY KEY,
  user_id ${integer} NOT NULL,
  csrf TEXT NOT NULL,
  expires_at ${integer} NOT NULL,
  updated_at ${integer} NOT NULL
);
CREATE TABLE IF NOT EXISTS api_tokens (
  id ${identity},
  name TEXT NOT NULL,
  hash TEXT NOT NULL UNIQUE,
  created_by TEXT NOT NULL,
  updated_at ${integer} NOT NULL
);
CREATE TABLE IF NOT EXISTS login_failures (
${loginFailureId}  name TEXT NOT NULL,
  at ${integer} NOT NULL
);
CREATE TABLE IF NOT EXISTS oauth_states (
  nonce TEXT PRIMARY KEY,
  expires_at ${integer} NOT NULL,
  updated_at ${integer} NOT NULL
);
CREATE TABLE IF NOT EXISTS installations (
  team_id TEXT PRIMARY KEY,
  team_name TEXT NOT NULL DEFAULT '',
  bot_user_id TEXT NOT NULL DEFAULT '',
  bot_id TEXT NOT NULL DEFAULT '',
  bot_token_enc TEXT,
  scopes TEXT NOT NULL DEFAULT '',
  installed_by TEXT NOT NULL DEFAULT '',
  installed_at ${integer},
  status TEXT NOT NULL CHECK (status IN ('pending', 'whitelisted', 'disabled')),
  trusted_bot_sender_json TEXT,
  last_seen_at ${integer},
  updated_at ${integer} NOT NULL
);
CREATE TABLE IF NOT EXISTS channels (
  team_id TEXT NOT NULL,
  channel_id TEXT NOT NULL,
  name TEXT NOT NULL DEFAULT '',
  is_private ${integer} NOT NULL DEFAULT 0,
  enabled ${integer} NOT NULL DEFAULT 0,
  bot_member ${integer} NOT NULL DEFAULT 0,
  updated_at ${integer} NOT NULL,
  PRIMARY KEY (team_id, channel_id)
);
CREATE TABLE IF NOT EXISTS blocked_members (
  team_id TEXT NOT NULL,
  channel_id TEXT NOT NULL,
  user_id TEXT NOT NULL,
  display_name TEXT NOT NULL DEFAULT '',
  updated_at ${integer} NOT NULL,
  PRIMARY KEY (team_id, channel_id, user_id)
);
CREATE TABLE IF NOT EXISTS config_versions (
  version ${integer} PRIMARY KEY,
  compiled_json TEXT NOT NULL,
  hash TEXT NOT NULL,
  content_hash TEXT NOT NULL,
  created_at ${integer} NOT NULL,
  actor TEXT NOT NULL,
  updated_at ${integer} NOT NULL
);
CREATE TABLE IF NOT EXISTS tool_instances (
  id TEXT PRIMARY KEY,
  team_id TEXT NOT NULL,
  kind TEXT NOT NULL,
  label TEXT NOT NULL,
  host TEXT,
  settings_json TEXT NOT NULL,
  credential_enc TEXT,
  credential_ver ${integer} NOT NULL DEFAULT 0,
  status TEXT NOT NULL CHECK (status IN ('enabled', 'disabled')),
  created_at ${integer} NOT NULL,
  updated_at ${integer} NOT NULL
);
CREATE TABLE IF NOT EXISTS tool_instance_status (
  instance_id TEXT PRIMARY KEY,
  state TEXT NOT NULL CHECK (state IN ('ready', 'error', 'blocked')),
  detail TEXT NOT NULL DEFAULT '',
  tools_count ${integer},
  credential_ver ${integer} NOT NULL,
  reporter TEXT NOT NULL,
  reported_at ${integer} NOT NULL
);
CREATE TABLE IF NOT EXISTS channel_tools (
  team_id TEXT NOT NULL,
  channel_id TEXT NOT NULL,
  kind TEXT NOT NULL,
  instance_id TEXT NOT NULL,
  updated_at ${integer} NOT NULL,
  PRIMARY KEY (team_id, channel_id, kind)
);
CREATE TABLE IF NOT EXISTS model_assignments (
  team_id TEXT NOT NULL,
  channel_id TEXT NOT NULL,
  model_key TEXT NOT NULL,
  updated_at ${integer} NOT NULL,
  PRIMARY KEY (team_id, channel_id)
);
CREATE TABLE IF NOT EXISTS channel_reply_settings (
  team_id TEXT NOT NULL,
  channel_id TEXT NOT NULL,
  auto_replies ${integer} NOT NULL CHECK (auto_replies IN (0, 1)),
  updated_at ${integer} NOT NULL,
  PRIMARY KEY (team_id, channel_id)
);
CREATE TABLE IF NOT EXISTS prompt_assignments (
  team_id TEXT NOT NULL,
  channel_id TEXT NOT NULL,
  text TEXT NOT NULL,
  updated_at ${integer} NOT NULL,
  PRIMARY KEY (team_id, channel_id)
);
CREATE TABLE IF NOT EXISTS provider_requests (
  id TEXT PRIMARY KEY,
  instance TEXT NOT NULL,
  day TEXT NOT NULL,
  completed_at ${integer} NOT NULL,
  received_at ${integer} NOT NULL,
  team_id TEXT,
  channel_id TEXT,
  root_ts TEXT,
  run_id TEXT,
  run_seq ${integer},
  attempt ${integer},
  mode TEXT NOT NULL,
  requester_user_id TEXT,
  model TEXT NOT NULL,
  route TEXT NOT NULL,
  connection TEXT NOT NULL,
  status ${integer} NOT NULL,
  duration_ms ${integer} NOT NULL,
  outcome TEXT NOT NULL,
  input_tokens ${integer},
  output_tokens ${integer}
);
CREATE INDEX IF NOT EXISTS provider_requests_by_day ON provider_requests (day, team_id, channel_id);
CREATE INDEX IF NOT EXISTS provider_requests_by_run ON provider_requests (run_id, attempt);
CREATE TABLE IF NOT EXISTS answer_feedback (
  run_id TEXT NOT NULL,
  user_id TEXT NOT NULL,
  team_id TEXT NOT NULL,
  channel_id TEXT NOT NULL,
  root_ts TEXT NOT NULL,
  answer_ts TEXT NOT NULL,
  vote TEXT NOT NULL CHECK (vote IN ('up', 'down')),
  updated_at ${integer} NOT NULL,
  PRIMARY KEY (run_id, user_id)
);
CREATE TABLE IF NOT EXISTS cost_runs (
  run_id TEXT NOT NULL,
  attempt ${integer} NOT NULL,
  instance TEXT NOT NULL,
  day TEXT NOT NULL,
  completed_at ${integer} NOT NULL,
  received_at ${integer} NOT NULL,
  team_id TEXT,
  channel_id TEXT,
  root_ts TEXT,
  mode TEXT NOT NULL,
  model TEXT,
  requester_user_id TEXT,
  input_tokens ${integer},
  output_tokens ${integer},
  cache_read_tokens ${integer},
  cache_creation_tokens ${integer},
  estimate_usd ${real},
  cost_basis TEXT,
  outcome TEXT NOT NULL,
  PRIMARY KEY (run_id, attempt)
);
CREATE INDEX IF NOT EXISTS cost_runs_by_day ON cost_runs (day, team_id, channel_id);
CREATE TABLE IF NOT EXISTS audit (
  id ${auditId},
  at ${integer} NOT NULL,
  actor TEXT NOT NULL,
  action TEXT NOT NULL,
  target TEXT NOT NULL,
  detail_json TEXT NOT NULL,
  config_version ${integer},
  updated_at ${integer} NOT NULL
);

CREATE TABLE IF NOT EXISTS channel_memory_state (
 team_id TEXT NOT NULL REFERENCES installations(team_id) ON DELETE CASCADE,
 channel_id TEXT NOT NULL, next_id ${integer} NOT NULL DEFAULT 1, revision ${integer} NOT NULL DEFAULT 0,
 PRIMARY KEY(team_id,channel_id));
CREATE TABLE IF NOT EXISTS channel_memory (
 team_id TEXT NOT NULL REFERENCES installations(team_id) ON DELETE CASCADE,
 channel_id TEXT NOT NULL, id ${integer} NOT NULL, entry_json TEXT NOT NULL,
 PRIMARY KEY(team_id,channel_id,id));
CREATE TABLE IF NOT EXISTS channel_commands (
 id TEXT PRIMARY KEY, team_id TEXT NOT NULL REFERENCES installations(team_id) ON DELETE CASCADE,
 channel_id TEXT NOT NULL, actor TEXT NOT NULL, source_ts TEXT NOT NULL, thread_ts TEXT NOT NULL,
 outcome_json TEXT NOT NULL, committed_at ${integer} NOT NULL);
CREATE TABLE IF NOT EXISTS channel_command_aliases (
 team_id TEXT NOT NULL REFERENCES installations(team_id) ON DELETE CASCADE,
 alias TEXT NOT NULL, command_id TEXT NOT NULL REFERENCES channel_commands(id) ON DELETE CASCADE,
 PRIMARY KEY(team_id,alias));
CREATE TABLE IF NOT EXISTS channel_command_receipts (
 id TEXT PRIMARY KEY, team_id TEXT NOT NULL REFERENCES installations(team_id) ON DELETE CASCADE,
 channel_id TEXT NOT NULL, thread_ts TEXT NOT NULL, body TEXT,
 state TEXT NOT NULL DEFAULT 'pending', lease TEXT, lease_until ${integer} NOT NULL DEFAULT 0,
 attempts ${integer} NOT NULL DEFAULT 0, slack_ts TEXT, committed_at ${integer} NOT NULL,
 last_error TEXT);
CREATE TABLE IF NOT EXISTS channel_command_receipt_tables (
 receipt_id TEXT PRIMARY KEY REFERENCES channel_command_receipts(id) ON DELETE CASCADE,
 table_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS channel_config_grants (
 id TEXT PRIMARY KEY, team_id TEXT NOT NULL REFERENCES installations(team_id) ON DELETE CASCADE,
 channel_id TEXT NOT NULL, actor TEXT NOT NULL, thread_ts TEXT NOT NULL,
 epoch ${integer} NOT NULL, expires_at ${integer} NOT NULL);
CREATE TABLE IF NOT EXISTS channel_config_sessions (
 id TEXT PRIMARY KEY, team_id TEXT NOT NULL REFERENCES installations(team_id) ON DELETE CASCADE,
 channel_id TEXT NOT NULL, actor TEXT NOT NULL, thread_ts TEXT NOT NULL,
 epoch ${integer} NOT NULL, expires_at ${integer} NOT NULL, fingerprint TEXT NOT NULL,
 payload_hash TEXT, result_json TEXT);
`;
}
