/**
 * Fake upstream of the `tools` suite (T3): one HTTPS server that the egress
 * proxy reaches under the real service host names (Docker network aliases).
 * It answers only the requests the CLI runtime makes for one representative
 * read per tool kind (five for GitLab), with fixtures that hold only the response fields the
 * runtime reads. Every request is recorded with the instances whose
 * credential it carried, never with a header value.
 */
import type { IncomingMessage, ServerResponse } from 'node:http';

